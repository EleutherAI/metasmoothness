def say(s=""):
    print(s); lines.append(s)


def perq(run, sub, min_rows=20):
    """Per-query QLD (filter_change - random_mean) from a merged summary, ordered by query, or None."""
    if run in EXCL:
        return None
    p = E / run / sub / "filter_summary.csv"
    if not p.is_file():
        return None
    rows = sorted(csv.DictReader(open(p)), key=lambda r: int(float(r["query"])))
    d = np.array([float(r["filter_change"]) - float(r["random_mean"]) for r in rows])
    d = d[np.isfinite(d)]
    return d if len(d) >= min_rows else None


def fit_pl(ns, ys):
    x, y = np.log(ns), np.log(ys); A = np.vstack([x, np.ones_like(x)]).T
    (a, b), *_ = np.linalg.lstsq(A, y, rcond=None); pred = A @ np.array([a, b])
    return a, math.exp(b), 1 - ((y - pred) ** 2).sum() / ((y - y.mean()) ** 2).sum()


def boot_alpha(ns, data, nboot=2000):
    out = []
    for _ in range(nboot):
        idx = rng.integers(0, 20, 20); yb = np.array([d[idx].mean() for d in data])
        if (yb > 0).all():
            out.append(fit_pl(ns, yb)[0])
    return np.percentile(out, [2.5, 97.5]) if out else (float("nan"), float("nan"))


def series(runs, sub, ns=None, alias=None):
    pts = []
    for n, run in runs.items():
        if ns is not None and n not in ns:
            continue
        s = alias.get((n, sub), sub) if alias else sub
        d = perq(run, s)
        if d is not None:
            pts.append((n, d))
    return np.array([n for n, _ in pts]), [d for _, d in pts]


