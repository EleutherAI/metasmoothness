def joint(name, pts):
    pts = [(n, k, d) for n, k, d in pts if d is not None]
    ys = np.array([d.mean() for *_, d in pts]); n = len(pts)
    if n < 5 or (ys <= 0).any():
        say(f"- {name}: insufficient points ({n})"); return
    def design(P, full): return np.array([[math.log(k), math.log(nn), 1.0] if full else [math.log(k), 1.0] for nn, k, _ in P])
    def fit(P, y, full):
        X = design(P, full); coef, *_ = np.linalg.lstsq(X, np.log(y), rcond=None); res = np.log(y) - X @ coef
        return coef, float((res ** 2).sum()), 1 - float((res ** 2).sum()) / float(((np.log(y) - np.log(y).mean()) ** 2).sum())
    def loo(full, leave):
        errs = []
        for out in itertools.combinations(range(n), leave):
            m = [i for i in range(n) if i not in out]
            coef, *_ = fit([pts[i] for i in m], ys[m], full)
            errs += [abs(math.exp(design([pts[i]], full)[0] @ coef) - ys[i]) / ys[i] for i in out]
        return float(np.mean(errs))
    cf, rss_f, r2_f = fit(pts, ys, True); cr, rss_r, r2_r = fit(pts, ys, False)
    F = (rss_r - rss_f) / (rss_f / (n - 3)); pF = 1 - fdist.cdf(F, 1, n - 3)
    aic = lambda rss, p: n * math.log(rss / n) + 2 * p
    boots = []
    for _ in range(2000):
        idx = rng.integers(0, 20, 20); yb = np.array([d[idx].mean() for *_, d in pts])
        if (yb > 0).all():
            boots.append(fit(pts, yb, True)[0])
    lo, hi = np.percentile(np.array(boots), [2.5, 97.5], axis=0)
    say(f"- {name} ({n} points): alpha = {cf[0]:.3f} [{lo[0]:.3f}, {hi[0]:.3f}], beta = {cf[1]:.3f} [{lo[1]:.3f}, {hi[1]:.3f}], R^2 = {r2_f:.3f}; "
        f"beta=0 model: alpha = {cr[0]:.3f}, R^2 = {r2_r:.3f}, F = {F:.2f} (p = {pF:.3f}), AIC full/reduced = {aic(rss_f,3):.1f}/{aic(rss_r,2):.1f}; "
        f"leave-1-out rel. error full/reduced = {loo(True,1):.3f}/{loo(False,1):.3f}; leave-2-out = {loo(True,2):.3f}/{loo(False,2):.3f}")


