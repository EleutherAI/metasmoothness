def lds_pts(scorer):
    out = []
    for r in rows:
        if r.get("model") != "gpt2" or float(r.get("logit_scale") or 1.0) != 1.0: continue
        l, y, st = (r.get(f"{scorer}_lds") or "").strip(), (r.get(f"filter_{scorer}_delta") or "").strip(), (r.get("steps") or "").strip()
        if l and y and st: out.append((float(l), float(y), int(st)))
    return np.array(out)


def rho_ci(x, y):
    bs = [spearmanr(x[i], y[i]).statistic for i in (rng.integers(0, len(x), len(x)) for _ in range(BOOT)) if len(set(i)) > 2]
    return spearmanr(x, y).statistic, np.percentile(bs, 2.5), np.percentile(bs, 97.5)


